"""Deterministic checks for the skill-selection corpus.

Hosts pick a skill from its name and description alone. These checks cannot
tell whether a model will pick the right skill; they check that the corpus is
well formed, that every core skill has prompts for and against it, that the
descriptions' `Not for ... (use X)` hand-offs form a sane graph, and that every
pair of skills whose triggers share wording has a prompt that separates them.
The model-backed `selection` suite in evals/behavior runs the same prompts.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from itertools import combinations
from pathlib import Path
import re

from evals.behavior import runner
from scripts import validate

REPO_ROOT = validate.REPO_ROOT
CATALOGUE = runner.SUITES["selection"]["catalogue"]
CASES = runner.SUITES["selection"]["cases"]
INSTALLER = REPO_ROOT / "npm/mastermind/bin/install.js"

ANSWER_PREFIX = "Skill: "
NONE = "none"
CONFLICT_PREFIX = "sel-conflict-"
CORE_MIN_POSITIVE = 2
CORE_MIN_NEGATIVE = 2
OTHER_MIN_POSITIVE = 1
OTHER_MIN_NEGATIVE = 1

# Shared trigger wording is a coarse sign that two skills compete for the same
# prompt. The threshold was set by reading the current pairs: at 0.2 every pair
# flagged is one a person could plausibly confuse. It finds candidates to
# write a prompt for; it does not measure how a model routes.
OVERLAP_THRESHOLD = 0.2
_STOPWORDS = frozenset(
    "a an and any are as asked at be before by for from how in into is it its "
    "not of on one or that the their there this to use used when whether which "
    "while who with without what your after".split()
)

CATALOGUE_HEADER = """\
# Skill selection probe

Generated by `python -m evals.selection --write` from every SKILL.md. Do not
edit by hand.

You are choosing which skill to load for the user's message. A host gives you
only these names and descriptions. Do not carry out the request and do not ask
a question. Reply with exactly one line: `Skill: <name>` for the one skill whose
description fits the message best, or `Skill: none` when none fits.

## Skills
"""


@dataclass(frozen=True)
class Skill:
    name: str
    description: str
    path: Path

    @property
    def trigger(self) -> str:
        return self.description.split("Not for", 1)[0]

    @property
    def referrals(self) -> tuple[str, ...]:
        return tuple(validate.description_referrals(self.description))


@dataclass(frozen=True)
class Case:
    id: str
    prompt: str
    accept: frozenset[str]
    reject: frozenset[str]

    @property
    def conflict(self) -> bool:
        return self.id.startswith(CONFLICT_PREFIX)

    @property
    def tie(self) -> bool:
        return len(self.accept) > 1


@dataclass
class Report:
    problems: list[str] = field(default_factory=list)
    ties: list[Case] = field(default_factory=list)
    overlaps: list[tuple[float, str, str, str]] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)


def load_skills() -> dict[str, Skill]:
    skills: dict[str, Skill] = {}
    for artifact in validate.find_artifacts():
        if artifact.path.name != "SKILL.md" or artifact.name is None:
            continue
        description = artifact.frontmatter.get("description")
        if isinstance(description, str):
            skills[artifact.name] = Skill(artifact.name, description, artifact.path)
    return dict(sorted(skills.items()))


def core_skills(installer: Path = INSTALLER) -> frozenset[str]:
    text = installer.read_text(encoding="utf-8")
    match = re.search(r"const CORE_SKILLS = \[(.*?)\];", text, re.S)
    if match is None:
        raise ValueError(f"CORE_SKILLS not found in {installer}")
    return frozenset(re.findall(r'"([a-z0-9-]+)"', match.group(1)))


def render_catalogue(skills: dict[str, Skill]) -> str:
    lines = [f"- `{skill.name}`: {skill.description}" for skill in skills.values()]
    return CATALOGUE_HEADER + "\n" + "\n".join(lines) + "\n"


def _answer_names(phrases: list[str], label: str, case_id: str, problems: list[str]) -> set[str]:
    names: set[str] = set()
    for phrase in phrases:
        if not phrase.startswith(ANSWER_PREFIX):
            problems.append(f"{case_id}: {label} phrase {phrase!r} must start with {ANSWER_PREFIX!r}")
            continue
        names.add(phrase[len(ANSWER_PREFIX):])
    return names


def load_cases(path: Path = CASES, problems: list[str] | None = None) -> list[Case]:
    problems = [] if problems is None else problems
    cases: list[Case] = []
    for record in runner.load_case_records(path, suite_name="selection"):
        case_id = record["id"]
        expect = record["expect"]
        groups = expect.get("contains_any", [])
        if ("contains" in expect) == bool(groups) or len(expect.get("contains", [None])) != 1 or len(groups) > 1:
            problems.append(f"{case_id}: name the expected skill with one `contains` phrase or one `contains_any` group")
            continue
        accept = _answer_names(expect.get("contains", []) or groups[0], "expected", case_id, problems)
        reject = _answer_names(expect.get("not_contains", []), "rejected", case_id, problems)
        cases.append(Case(case_id, record["input"]["prompt"], frozenset(accept), frozenset(reject)))
    return cases


def _tokens(text: str) -> set[str]:
    words = re.findall(r"[a-z][a-z0-9+-]*", text.lower())
    return {word[:-1] if len(word) > 3 and word.endswith("s") else word for word in words if word not in _STOPWORDS}


def trigger_overlap(a: Skill, b: Skill) -> tuple[float, set[str]]:
    left, right = _tokens(a.trigger), _tokens(b.trigger)
    union = left | right
    shared = left & right
    return (len(shared) / len(union) if union else 0.0), shared


def _cycles(graph: dict[str, tuple[str, ...]]) -> list[list[str]]:
    """Simple referral cycles of three or more skills.

    A pair that names each other draws one boundary from both sides, which is
    the point. A longer loop means each hands the prompt on and none keeps it.
    """
    found: set[tuple[str, ...]] = set()

    def walk(start: str, node: str, path: list[str]) -> None:
        for nxt in graph.get(node, ()):
            if nxt == start and len(path) >= 3:
                pivot = path.index(min(path))
                found.add(tuple(path[pivot:] + path[:pivot]))
            elif nxt not in path and nxt > start:
                walk(start, nxt, path + [nxt])

    for start in sorted(graph):
        walk(start, start, [start])
    return [list(cycle) for cycle in sorted(found)]


def check(
    skills: dict[str, Skill] | None = None,
    cases: list[Case] | None = None,
    core: frozenset[str] | None = None,
    catalogue: Path | None = CATALOGUE,
) -> Report:
    report = Report()
    problems = report.problems
    skills = load_skills() if skills is None else skills
    cases = load_cases(problems=problems) if cases is None else cases
    core = core_skills() if core is None else core
    known = set(skills)

    if catalogue is not None:
        current = catalogue.read_text(encoding="utf-8") if catalogue.is_file() else ""
        if current != render_catalogue(skills):
            problems.append(f"{catalogue.relative_to(REPO_ROOT)} is stale; run `python -m evals.selection --write`")

    for left, right in combinations(sorted(known), 2):
        if right.startswith(left) or left.startswith(right):
            problems.append(f"skill names {left} and {right} share a prefix, so answer phrases cannot tell them apart")

    for name in sorted(core - known):
        problems.append(f"core profile names {name}, which has no SKILL.md")

    positives = {name: 0 for name in known}
    negatives = {name: 0 for name in known}
    separated: set[frozenset[str]] = set()
    for case in cases:
        for name in sorted((case.accept | case.reject) - known - {NONE}):
            problems.append(f"{case.id}: {name} is not a shipped skill")
        if NONE in case.accept and len(case.accept) > 1:
            problems.append(f"{case.id}: 'none' cannot share a tie with a skill")
        if case.accept & case.reject:
            problems.append(f"{case.id}: {sorted(case.accept & case.reject)} both expected and rejected")
        if not case.reject:
            problems.append(f"{case.id}: name at least one near miss to reject")
        for name in sorted(case.accept - {NONE}):
            if name in case.prompt:
                problems.append(f"{case.id}: the prompt names {name}, so the case tests nothing")
        for name in case.accept & known:
            positives[name] += 1
        for name in case.reject & known:
            negatives[name] += 1
        for pair in combinations(sorted((case.accept | case.reject) & known), 2):
            separated.add(frozenset(pair))
        if case.tie:
            report.ties.append(case)
        elif case.conflict:
            (winner,) = case.accept
            if not any(winner in skills[loser].referrals for loser in case.reject if loser in skills):
                problems.append(
                    f"{case.id}: no rejected skill's description says 'Not for ... (use {winner})'; "
                    "write the tie-break into a description or declare the case a tie"
                )

    for name in sorted(known):
        need_pos, need_neg = (
            (CORE_MIN_POSITIVE, CORE_MIN_NEGATIVE) if name in core else (OTHER_MIN_POSITIVE, OTHER_MIN_NEGATIVE)
        )
        if positives[name] < need_pos:
            problems.append(f"{name}: {positives[name]} prompt(s) expect it; need {need_pos}")
        if negatives[name] < need_neg:
            problems.append(f"{name}: {negatives[name]} prompt(s) reject it; need {need_neg}")

    graph = {name: skill.referrals for name, skill in skills.items()}
    for name, targets in graph.items():
        for target in targets:
            if name in core and target in known and target not in core:
                # Reported, not failed: the hand-off still reads sensibly, but a
                # core install has nothing by that name to hand off to.
                report.notes.append(f"{name} is in core but its description sends the host to {target}, which core does not install")
    for cycle in _cycles(graph):
        problems.append("referral loop with no owner: " + " -> ".join(cycle + [cycle[0]]))

    for left, right in combinations(sorted(known), 2):
        score, shared = trigger_overlap(skills[left], skills[right])
        if score < OVERLAP_THRESHOLD:
            continue
        report.overlaps.append((score, left, right, ", ".join(sorted(shared))))
        linked = right in graph[left] or left in graph[right]
        if not linked and frozenset((left, right)) not in separated:
            problems.append(
                f"{left} and {right} share trigger words ({', '.join(sorted(shared))}) and no description "
                "or prompt separates them; add a case that expects one and rejects the other"
            )
    report.overlaps.sort(reverse=True)
    return report
